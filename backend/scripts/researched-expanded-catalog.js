function specsFromVariant(variant, type) {
  const parts = variant.split(' · ');
  const capacities = [...variant.matchAll(/\b(\d+(?:\.\d+)?\s?(?:GB|TB))\b/gi)].map((match) => match[1].replace(/\s/g, ''));
  const memory = capacities.length > 1 ? capacities[0] : '';
  const storage = capacities.at(-1) || '';
  const graphics = variant.match(/RTX\s?\d{3,4}(?:\s?Ti)?/i)?.[0] || '';
  const display = variant.match(/\d+(?:\.\d+)?-inch[^·]*/i)?.[0]?.trim() || '';
  return {
    memory: memory ? memory + ' RAM' : '',
    storage,
    processor: type === 'Laptops' ? parts[0] : '',
    camera: graphics ? 'NVIDIA GeForce ' + graphics : '',
    display,
  };
}

